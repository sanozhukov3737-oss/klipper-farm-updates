"""Apply the reviewed R213 release sequence over the exact sequence-166 candidate with R212 applied.

Sequence 166 is published, so the janitor from R212 would reach nobody. This raises the packaged
channel to 167 and the identity to R15.17, the released application version 1.15.17.

It carries one overlay: deleted printers no longer leave local traces behind. On the farm in question
ten file caches of seventeen belonged to printers that no longer exist, because the database bridge
could not list keys and could not delete one, so nothing could ever have removed them. The cleanup now
runs once per launch, never on an empty printer list, and reports to the journal. The TV dashboard
also retries a failed camera instead of showing it blank until restart.

The workflow's three sequence-bound expectations move with this and R213 joins the chain.
"""
from pathlib import Path, PurePosixPath
import hashlib
import json
import sys

root = Path(sys.argv[1]).resolve()
overlay = Path(__file__).resolve().parent
manifest = json.loads((overlay / 'source-manifest.json').read_text(encoding='utf-8'))
channel = json.loads((root / 'UPDATE-CHANNEL.json').read_text(encoding='utf-8-sig'))
expected_channel = {
    'endpoint': 'https://github.com/sanozhukov3737-oss/klipper-farm-updates/releases/latest/download/update-v20.json',
    'publicKeyHex': '28e0124c33f42704483d1aac89af829c44a00ef5dbc2e93dff630befddd495eb',
    'channel': 'stable',
    'installedSequence': 166,
}
if channel != expected_channel:
    raise SystemExit('Expected exact unchanged trust channel at this sequence-166 candidate')
identity = (root / 'RELEASE-BUILD-ID.txt').read_text(encoding='utf-8-sig').strip()
if identity != manifest['baseBuildId']:
    raise SystemExit('Expected the accepted sequence-166 candidate with R212 applied before R213')


def canonical(data):
    return data.replace(b'\r\n', b'\n')


def digest(data):
    return hashlib.sha256(canonical(data)).hexdigest()


rows = []
for row in manifest['files']:
    path = PurePosixPath(row['path'])
    if path.is_absolute() or '..' in path.parts or '\\' in row['path']:
        raise SystemExit('Unsafe source path')
    target = root.joinpath(*path.parts)
    source = overlay.joinpath('changes', *path.parts)
    if not source.is_file() or digest(source.read_bytes()) != row['sha256']:
        raise SystemExit('Candidate source checksum differs: ' + row['path'])
    before = row.get('beforeSha256')
    if before is not None:
        current = digest(target.read_bytes()) if target.is_file() else None
        if current not in (before, row['sha256']):
            raise SystemExit('Existing source differs; refusing to overwrite: ' + row['path'])
    rows.append((target, source))
for target, source in rows:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(canonical(source.read_bytes()))
print('Applied reviewed R213 release sequence over the exact sequence-166 candidate with R212 applied.')
