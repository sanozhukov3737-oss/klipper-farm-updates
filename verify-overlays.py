#!/usr/bin/env python3
"""Enforce the rules a reviewed overlay must satisfy before it is applied.

An overlay carries source changes only. Build output is never part of it: dist/, target/, node_modules/
and the artifacts derived from them are produced by the workflow from the sources it has just applied, so
shipping them in the payload would let a stale bundle travel with a source patch, and a committed
__pycache__ or .exe cannot be reviewed as source at all.

Run from the repository root:

    python verify-overlays.py .
    python verify-overlays.py . --quiet

Exit code 0 means every overlay complies; 1 means at least one violation, each printed as
"<overlay>: <path>: <reason>". Every directory holding a source-manifest.json is checked, so overlays
added later are covered without editing this script.

Four rules, each verified to hold across the overlays already committed so a clean run is meaningful:

  path shape      declared paths stay inside the applied tree (relative, POSIX, no "..").
  no build output neither the payload nor the manifest may name a generated directory, file or suffix.
  payload match   the payload holds exactly the files the manifest declares — no strays, no absences.
  integrity       each declared sha256 matches the payload after CRLF/LF canonicalisation, and a declared
                  byte count, when present, is the canonical length.

Deliberately not enforced: that buildId equals baseBuildId. The release-sequence overlays (r155, r160,
r184, ...) legitimately advance it, so the rule would only produce false alarms. Legacy manifests
without a schema field are accepted as they are; history is reported, not rewritten.
"""
from pathlib import Path, PurePosixPath
import argparse
import hashlib
import json
import sys

MANIFEST = 'source-manifest.json'
PAYLOAD = 'changes'

# Directories whose contents are produced by a build or by running a script.
FORBIDDEN_DIRECTORIES = {
    'dist',
    'target',
    'node_modules',
    'binaries',
    '__pycache__',
    '.cache',
    '.pytest_cache',
    'coverage',
}

# Files that only exist as build output, packaging or machine-local state.
FORBIDDEN_NAMES = {
    'BUILD-PROVENANCE.json',
    'DIST-V20-LOCK.json',
    'CACHEDIR.TAG',
    '.kf-v1144-complete',
}

FORBIDDEN_SUFFIXES = {
    '.exe', '.dll', '.pdb', '.lib', '.rlib', '.node',
    '.pyc', '.pyo',
    '.zip', '.tar', '.gz', '.7z',
    '.log',
}


def canonical(data):
    return data.replace(b'\r\n', b'\n')


def digest(data):
    return hashlib.sha256(canonical(data)).hexdigest()


class Report:
    def __init__(self):
        self.failures = []

    def fail(self, overlay, subject, reason):
        self.failures.append((overlay.name, subject, reason))


def build_output_reason(path):
    """Return why a relative path is build output, or None when it is a normal source path."""
    for part in path.parts[:-1]:
        if part.lower() in FORBIDDEN_DIRECTORIES:
            return f'is build output: "{part}/" is generated, not authored'
    name = path.parts[-1]
    if name in FORBIDDEN_NAMES:
        return f'is build output: "{name}" is generated by the build'
    suffix = PurePosixPath(name).suffix.lower()
    if suffix in FORBIDDEN_SUFFIXES:
        return f'is build output or machine-local state: "{suffix}" files are not source'
    return None


def safe_relative(report, overlay, declared):
    if '\\' in declared:
        report.fail(overlay, declared, 'uses backslashes; overlay paths are POSIX relative paths')
        return None
    path = PurePosixPath(declared)
    if path.is_absolute():
        report.fail(overlay, declared, 'is absolute; overlay paths are relative to the applied app root')
        return None
    if '..' in path.parts:
        report.fail(overlay, declared, 'escapes with ".."; an overlay may only touch the applied tree')
        return None
    if not path.parts:
        report.fail(overlay, declared, 'is empty')
        return None
    return path


def verify(overlay, report):
    try:
        manifest = json.loads((overlay / MANIFEST).read_text(encoding='utf-8'))
    except (OSError, ValueError) as error:
        report.fail(overlay, MANIFEST, f'cannot be read as JSON: {error}')
        return 0

    rows = manifest.get('files')
    if not isinstance(rows, list) or not rows:
        report.fail(overlay, MANIFEST, 'declares no files')
        return 0

    payload_root = overlay / PAYLOAD
    declared = {}
    for row in rows:
        if not isinstance(row, dict) or not isinstance(row.get('path'), str):
            report.fail(overlay, MANIFEST, 'has a file entry without a path')
            continue
        raw = row['path']
        if raw in declared:
            report.fail(overlay, raw, 'is declared twice')
            continue
        path = safe_relative(report, overlay, raw)
        if path is None:
            continue
        reason = build_output_reason(path)
        if reason:
            report.fail(overlay, raw, reason)
        declared[raw] = row

        source = payload_root.joinpath(*path.parts)
        if not source.is_file():
            report.fail(overlay, raw, 'is declared but missing from the payload')
            continue
        data = source.read_bytes()
        expected = row.get('sha256')
        if expected != digest(data):
            report.fail(overlay, raw, 'payload checksum does not match the manifest')
        size = row.get('bytes')
        if isinstance(size, int) and size != len(canonical(data)):
            report.fail(overlay, raw, f'declared {size} bytes but the payload has {len(canonical(data))}')

    if payload_root.is_dir():
        for entry in sorted(payload_root.rglob('*')):
            if not entry.is_file():
                continue
            relative = entry.relative_to(payload_root).as_posix()
            reason = build_output_reason(PurePosixPath(relative))
            if reason:
                report.fail(overlay, relative, reason)
            if relative not in declared:
                report.fail(overlay, relative, 'sits in the payload but is not declared in the manifest')
    return len(declared)


def main():
    parser = argparse.ArgumentParser(description='Verify that overlays carry source changes only.')
    parser.add_argument('root', nargs='?', default='.', help='repository root to scan')
    parser.add_argument('--quiet', action='store_true', help='print only failures and the summary')
    arguments = parser.parse_args()

    root = Path(arguments.root).resolve()
    if not root.is_dir():
        print(f'not a directory: {root}', file=sys.stderr)
        return 1

    overlays = sorted(path.parent for path in root.glob('*/' + MANIFEST))
    if not overlays:
        print(f'no overlays found under {root}', file=sys.stderr)
        return 1

    report = Report()
    total = 0
    for overlay in overlays:
        count = verify(overlay, report)
        total += count
        if not arguments.quiet:
            print(f'{overlay.name}: {count} declared source files')

    if report.failures:
        print('', file=sys.stderr)
        for overlay, subject, reason in report.failures:
            print(f'{overlay}: {subject}: {reason}', file=sys.stderr)
        print(f'\n{len(report.failures)} violation(s) across {len(overlays)} overlays.', file=sys.stderr)
        return 1

    print(f'overlay rules OK: {len(overlays)} overlays, {total} declared source files, no build output')
    return 0


if __name__ == '__main__':
    sys.exit(main())
